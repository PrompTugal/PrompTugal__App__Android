#!/usr/bin/env bash
# Lists every runtime dependency of the release build with its licence, read from each artifact's
# POM in the Gradle cache (no Gradle plugin, no network beyond what `./gradlew` itself needs).
# Writes docs/security/licences.md. Run from anywhere:  scripts/licences.sh
# Needs: JDK 17, the Android SDK (ANDROID_HOME), python3. Run a build first so the POMs are cached.
# Flags: anything not Apache-2.0, MIT, BSD-2/3 or ISC-like, or with no licence in its POM or parents.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=docs/security/licences.md
CACHE="${GRADLE_USER_HOME:-$HOME/.gradle}/caches/modules-2/files-2.1"
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
./gradlew --console=plain -q :app:dependencies --configuration releaseRuntimeClasspath > "$tmp"
python3 -I - "$tmp" "$CACHE" "$OUT" <<'PY'
import re, sys, glob, os
import xml.etree.ElementTree as ET

tree_file, cache, out = sys.argv[1:4]

# 1. resolved coordinates from the dependency tree
coords = {}
for line in open(tree_file, encoding='utf-8'):
    if '(c)' in line or '(n)' in line:
        continue
    m = re.search(r'([\w.\-]+):([\w.\-]+)(?::([\w.\-+]+))?(?: -> ([\w.\-+]+))?(?: \(\*\))?\s*$', line.rstrip())
    if not m or not re.match(r'^[|+\\ -]*[+\\]--- ', line) and not re.match(r'^[+\\]--- ', line):
        continue
    g, a, declared, resolved = m.groups()
    ver = resolved or declared
    if ver:
        coords[(g, a)] = ver
        # a "group:artifact -> ver" style line may be a project; ignore unresolved
deps = sorted(coords.items())

NS = '{http://maven.apache.org/POM/4.0.0}'
def find_pom(g, a, v):
    hits = glob.glob(os.path.join(cache, g, a, v, '*', f'{a}-{v}.pom'))
    return hits[0] if hits else None

def text(el, tag):
    c = el.find(NS + tag)
    if c is None:
        c = el.find(tag)
    return c.text.strip() if c is not None and c.text else None

def licences(g, a, v, depth=0):
    p = find_pom(g, a, v)
    if not p or depth > 5:
        return None, 'no POM in cache'
    root = ET.parse(p).getroot()
    out_l = []
    lic = root.find(NS + 'licenses')
    if lic is not None:
        for l in lic.findall(NS + 'license'):
            out_l.append((text(l, 'name') or '?', text(l, 'url') or ''))
    if out_l:
        return out_l, 'pom' if depth == 0 else 'parent pom'
    par = root.find(NS + 'parent')
    if par is not None:
        return licences(text(par, 'groupId'), text(par, 'artifactId'), text(par, 'version'), depth + 1)
    return None, 'no licence element'

OK = re.compile(r'apache|mit license|^mit$|bsd|isc|public domain', re.I)
rows, flagged = [], []
for (g, a), v in deps:
    ls, src = licences(g, a, v)
    if not ls:
        rows.append((f'{g}:{a}:{v}', 'UNKNOWN', src, 'FLAG: unknown'))
        flagged.append(f'{g}:{a}:{v} (unknown: {src})')
        continue
    names = '; '.join(n for n, _ in ls)
    urls = '; '.join(u for _, u in ls if u)
    ok = all(OK.search(n) or OK.search(u) for n, u in ls)
    rows.append((f'{g}:{a}:{v}', names, urls, '' if ok else 'FLAG: check'))
    if not ok:
        flagged.append(f'{g}:{a}:{v} ({names})')

with open(out, 'w', encoding='utf-8') as f:
    f.write('# Runtime dependency licences (release build)\n\n')
    f.write('Generated by `scripts/licences.sh` from `./gradlew :app:dependencies --configuration releaseRuntimeClasspath` '
            'and each artifact\'s POM (or parent POM) in the Gradle cache. Do not edit by hand.\n\n')
    f.write(f'{len(rows)} artifacts. Flagged: {len(flagged)}.\n\n')
    if flagged:
        f.write('## Flagged (not Apache-2.0, MIT or BSD, or unknown)\n\n')
        for x in flagged:
            f.write(f'- {x}\n')
        f.write('\n')
    f.write('| Artifact (group:artifact:version) | Licence | Licence URL | Flag |\n|---|---|---|---|\n')
    for r in rows:
        f.write('| ' + ' | '.join(c.replace('|', '/') for c in r) + ' |\n')
print(f'{len(rows)} artifacts, {len(flagged)} flagged -> {out}')
PY
