#!/usr/bin/env bash
# Known-vulnerability check of the release runtime dependencies against OSV.dev (public data only).
# Reads the group:artifact:version list that scripts/licences.sh writes into docs/security/licences.md
# (run that first, or pass --refresh to run it here), sends ONLY "group:artifact" and "version" to
# https://api.osv.dev (no project name, no paths, no secrets), and writes docs/security/vulns.md.
# Exit 0 = no known vulnerabilities, 1 = at least one, 2 = could not query OSV.
# Usage:  scripts/osv-check.sh [--refresh]
set -euo pipefail
cd "$(dirname "$0")/.."
[ "${1:-}" = "--refresh" ] && scripts/licences.sh
[ -f docs/security/licences.md ] || { echo "docs/security/licences.md missing: run scripts/licences.sh" >&2; exit 2; }
python3 -I - docs/security/licences.md docs/security/vulns.md <<'PY'
import json, re, sys, ssl, os, datetime, urllib.request, urllib.error

src, out = sys.argv[1:3]
coords = []
for line in open(src, encoding='utf-8'):
    m = re.match(r'^\| ([\w.\-]+):([\w.\-]+):([\w.\-+]+) \|', line)
    if m:
        coords.append(m.groups())
if not coords:
    sys.exit('no coordinates found in ' + src)

ctx = ssl.create_default_context(cafile=os.environ.get('SSL_CERT_FILE') or os.environ.get('REQUESTS_CA_BUNDLE') or None)
def call(url, body=None):
    req = urllib.request.Request(url, data=None if body is None else json.dumps(body).encode(),
                                 headers={'Content-Type': 'application/json', 'User-Agent': 'osv-check'})
    last = None
    for _ in range(4):
        try:
            with urllib.request.urlopen(req, timeout=60, context=ctx) as r:
                return json.load(r)
        except (urllib.error.URLError, TimeoutError) as e:
            last = e
    print('OSV unreachable:', last, file=sys.stderr)
    sys.exit(2)

queries = [{'package': {'name': f'{g}:{a}', 'ecosystem': 'Maven'}, 'version': v} for g, a, v in coords]
results = []
for i in range(0, len(queries), 500):
    results += call('https://api.osv.dev/v1/querybatch', {'queries': queries[i:i + 500]})['results']

found = {}   # (g,a,v) -> [ids]
for (g, a, v), r in zip(coords, results):
    ids = [x['id'] for x in r.get('vulns', [])]
    if ids:
        found[(g, a, v)] = ids

details = {}
for ids in found.values():
    for i in ids:
        if i not in details:
            details[i] = call('https://api.osv.dev/v1/vulns/' + i)

def fixed_in(d, name):
    fx = []
    for aff in d.get('affected', []):
        if aff.get('package', {}).get('name') != name:
            continue
        for rg in aff.get('ranges', []):
            fx += [e['fixed'] for e in rg.get('events', []) if 'fixed' in e]
    return ', '.join(sorted(set(fx))) or 'none listed'

def sev(d):
    s = d.get('database_specific', {}).get('severity')
    return s or ('CVSS ' + d['severity'][0]['score'].split('/')[0] if d.get('severity') else 'unrated')

now = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
with open(out, 'w', encoding='utf-8') as f:
    f.write('# Known vulnerabilities in release dependencies\n\n')
    f.write('Generated by `scripts/osv-check.sh` from the coordinates in `docs/security/licences.md` '
            f'against the public OSV.dev API on {now}. Do not edit by hand. Only `group:artifact` and the version '
            'were sent to OSV; no other data leaves the repository.\n\n')
    f.write(f'{len(coords)} artifacts checked. Artifacts with a known vulnerability: {len(found)}.\n\n')
    f.write('Scope: the `releaseRuntimeClasspath` (what ships in the APK/AAB). Build tooling (Android Gradle Plugin, '
            'Kotlin compiler, test libraries) and the Node CLI in `devices/` (no dependencies) are not covered. '
            'OSV lists a vulnerability by affected version range; it does not say the app calls the vulnerable code.\n\n')
    if not found:
        f.write('**Result: none known.**\n')
    else:
        f.write('| Artifact | Id | Severity | Fixed in | Summary |\n|---|---|---|---|---|\n')
        for (g, a, v), ids in sorted(found.items()):
            for i in ids:
                d = details[i]
                al = [x for x in d.get('aliases', []) if x.startswith('CVE-')]
                f.write(f"| {g}:{a}:{v} | {i}{' (' + ', '.join(al) + ')' if al else ''} | {sev(d)} | "
                        f"{fixed_in(d, g + ':' + a)} | {(d.get('summary') or '').replace('|', '/')[:140]} |\n")
print(f'{len(coords)} artifacts, {len(found)} with known vulnerabilities -> {out}')
sys.exit(1 if found else 0)
PY
